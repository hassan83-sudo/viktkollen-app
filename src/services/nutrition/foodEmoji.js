export function getFoodEmoji(name = '') {
  const normalized = String(name ?? '').normalize('NFD').replace(/[\u0300-\u036f]/g, '').toLowerCase()
  return foodEmojis.find(([pattern]) => pattern.test(normalized))?.[1] || '🍽️'
}
